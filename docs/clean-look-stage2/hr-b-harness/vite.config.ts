import { readdirSync, readFileSync, statSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import inertia from '@inertiajs/vite';
import tailwindcss from '@tailwindcss/vite';
import vue from '@vitejs/plugin-vue';
import { defineConfig, type Plugin } from 'vite';

const root = resolve(__dirname, '..');
const STUB = '\0cl2stub:';

function walk(dir: string, out: string[] = []) {
    for (const f of readdirSync(dir)) {
        const p = join(dir, f);
        statSync(p).isDirectory() ? walk(p, out) : /\.(vue|ts)$/.test(f) && out.push(p);
    }
    return out;
}

// Wayfinder files are generated by PHP; stub them: every named import becomes a route-like callable.
function stubs(): Plugin {
    const names = new Map<string, Set<string>>();
    const re = /import\s+(?:type\s+)?(\{[^}]*\}|[\w$]+|\*\s+as\s+[\w$]+)\s*from\s+'(@\/(?:routes|actions)[^']*)'/g;
    for (const file of walk(join(root, 'resources/js'))) {
        const src = readFileSync(file, 'utf8');
        for (const m of src.matchAll(re)) {
            const set = names.get(m[2]) ?? new Set();
            const braces = m[1].match(/\{([\s\S]*)\}/);
            braces?.[1].split(',').map((s) => s.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0]).filter(Boolean).forEach((n) => set.add(n));
            names.set(m[2], set);
        }
    }
    return {
        name: 'cl2-stubs',
        enforce: 'pre',
        resolveId(id) {
            const base = join(root, 'resources/js') + '/';
            const k = id.startsWith(base) ? '@/' + id.slice(base.length) : id;
            if (k.startsWith('@/routes') || k.startsWith('@/actions')) return STUB + k;
        },
        load(id) {
            if (!id.startsWith(STUB)) return;
            const key = id.slice(STUB.length);
            const list = [...(names.get(key) ?? [])];
            const mk = `const mk=(n)=>{const f=(...a)=>({url:'#',method:'get'});f.url=()=>'#';f.get=f.post=f.put=f.patch=f.delete=f.form=f.definition=()=>({url:'#',method:'get'});return new Proxy(f,{get:(t,k)=>k in t?t[k]:mk(String(k))})};`;
            return `${mk}\n${list.map((n) => `export const ${n}=mk('${n}');`).join('\n')}\nexport default mk('default');`;
        },
    };
}

// /h/<mock>: serve the Inertia shell with mocks/<mock>.json as the initial page; no PHP involved.
function shell(): Plugin {
    return {
        name: 'cl2-shell',
        configureServer(server) {
            server.middlewares.use(async (req, res, next) => {
                const m = req.url?.match(/^\/h\/([\w.-]+)/);
                if (!m) return next();
                const file = join(__dirname, 'mocks', `${m[1]}.json`);
                if (!existsSync(file)) { res.statusCode = 404; return res.end('no mock'); }
                const page = readFileSync(file, 'utf8').replace(/</g, '\\u003c');
                const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><script>try{if(localStorage.getItem('appearance')==='dark')document.documentElement.classList.add('dark')}catch(e){}</script><script type="module" src="/resources/js/app.ts"></script><link rel="stylesheet" href="/resources/css/app.css"></head><body><script data-page="app" type="application/json">${page}</script><div id="app"></div></body></html>`;
                res.setHeader('content-type', 'text/html');
                res.end(await server.transformIndexHtml(req.url!, html));
            });
        },
    };
}

export default defineConfig({
    root,
    configFile: false,
    server: { port: 5199, host: '127.0.0.1', strictPort: true, hmr: false, watch: null },
    optimizeDeps: { entries: ['resources/js/app.ts', 'resources/js/pages/**/*.vue'] },
    build: { outDir: join(__dirname, 'dist'), emptyOutDir: true, manifest: true, rollupOptions: { input: [join(root, 'resources/js/app.ts'), join(root, 'resources/css/app.css')] } },
    resolve: { alias: { '@': join(root, 'resources/js') } },
    plugins: [stubs(), shell(), inertia({ ssr: false }), tailwindcss(), vue()],
});
